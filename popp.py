def end_game(message, success):
    """Вывод концовки и завершение игры."""
    print("\n" + "=" * 40)
    if success:
        print("✅ УСПЕШНОЕ ЗАВЕРШЕНИЕ:")
    else:
        print("❌ КОНЕЦ ИГРЫ:")
    print(message)
    print("=" * 40)

def scene_inside(inventory):
    """Сцена 2: Внутри Хижины."""
    print("\n---")
    print("### Сцена 2: Внутри Хижины")
    print("Вы находитесь внутри хижины. На столе лежит **странный светящийся камень** и старая, пыльная **книга**.")

    while True:
        print("\n**2.** Что вы делаете?")
        print("1. Взять светящийся камень.")
        print("2. Прочитать старую книгу.")
        
        choice = input("*(Введите 1 или 2): *").strip()
        
        if choice == '1':
            print("\nВы берёте камень. Он тёплый и приятно светится. Внезапно вся хижина наполняется ярким светом. Вы чувствуете невероятную энергию и понимаете, что нашли **древний артефакт**. Внезапно вы оказываетесь **перенесены** на берег тёплого моря.")
            inventory.append("камень")
            end_game("Концовка 4: Магическое Спасение. Вы спасены и теперь обладаете могущественным артефактом.", success=True)
            return
        elif choice == '2':
            print("\nВы открываете книгу. Это **дневник** предыдущего владельца, который рассказывает о ловушке в подвале и о необходимости покинуть хижину до полуночи. Вы посмотрели на часы. **Почти полночь!**")
            print("Вы хватаете свои вещи и **выбегаете** из хижины. Убегая, вы слышите, как подвал обрушивается, но вам удалось спастись.")
            end_game("Концовка 5: Предупреждён — Вооружён. Вы избежали опасности благодаря информации и успешно продолжили свой путь.", success=True)
            return
        else:
            print("Неверный ввод. Пожалуйста, введите 1 или 2.")
            
def path_knock(inventory):
    """Путь 1: Постучать в дверь."""
    print("\n#### Путь 1: Постучать в дверь")
    print("Вы осторожно стучите. Дверь со скрипом открывается сама. Внутри темно, пахнет пылью и старостью.")

    while True:
        print("\n**1.1.** Что вы делаете?")
        print("1. Войти внутрь, чтобы осмотреться.")
        print("2. Остаться снаружи, чтобы подождать и посмотреть, не выйдет ли кто-нибудь.")
        
        choice = input("*(Введите 1 или 2): *").strip()
        
        if choice == '1':
            print("\nВы делаете шаг внутрь. Пол проваливается под вашей ногой, и вы падаете в **глубокий подвал**. Вы разбили голову и не можете выбраться.")
            end_game("Концовка 1: Заброшенная Ловушка. Ваше путешествие окончено.", success=False)
            return
        elif choice == '2':
            print("\nВы стоите у порога. Внезапно дверь захлопывается, и вы слышите **громкий рык** изнутри. Вы в панике убегаете в лес, ища другую дорогу.")
            end_game("Концовка 2: Испуганный Беглец. Вам удалось сбежать, но вы промокнете под дождем, который вот-вот начнётся.", success=True)
            return
        else:
            print("Неверный ввод. Пожалуйста, введите 1 или 2.")
            
def path_search_outside(inventory):
    """Путь 3: Попробовать отыскать что-нибудь полезное снаружи."""
    print("\n#### Путь 3: Попробовать отыскать что-нибудь полезное снаружи")
    print("Вы осматриваете землю возле крыльца. Среди гниющих листьев вы находите **крепкий кусок металлической проволоки**.")
    inventory.append("проволока")
    print(f"(Ваш инвентарь: {', '.join(inventory)})")

    while True:
        print("\n**1.3.** Что вы делаете?")
        print("1. Использовать проволоку, чтобы попытаться открыть дверь.")
        print("2. Отказаться от этой идеи и постучать в дверь.")
        
        choice = input("*(Введите 1 или 2): *").strip()
        
        if choice == '1':
            print("\nВы вставляете проволоку в замочную скважину и после нескольких минут ковыряния, слышите **щелчок**. Дверь открыта. Внутри темно, но вы видите на столе тускло мерцающий **камень**.")
            scene_inside(inventory)
            return
        elif choice == '2':
            path_knock(inventory)
            return
        else:
            print("Неверный ввод. Пожалуйста, введите 1 или 2.")

def path_search_entrance(inventory):
    """Путь 2: Поискать другой вход."""
    print("\n#### Путь 2: Поискать другой вход")
    print("Вы обходите хижину и находите **маленькое, заколоченное окно** на задней стене.")

    while True:
        print("\n**1.2.** Что вы делаете?")
        print("1. Попытаться выбить доски и влезть через окно.")
        print("2. Вернуться к входной двери и воспользоваться ею.")
        
        choice = input("*(Введите 1 или 2): *").strip()
        
        if choice == '1':
            print("\nВы с трудом выбиваете доски. Окно открывается. Внутри горит тусклый фонарь. Вы проникаете в хижину. **Вы нашли ключ.**")
            inventory.append("ключ")
            scene_inside(inventory)
            return
        elif choice == '2':
            print("\nВы возвращаетесь к двери, стучите, но она не открывается. Вы слышите тихий **смех** изнутри. Вы решаете идти дальше по лесу, чтобы найти лучшее убежище.")
            end_game("Концовка 3: Избежавшая Опасность. Вы остались живы, но теперь в пути ночью.", success=True)
            return
        else:
            print("Неверный ввод. Пожалуйста, введите 1 или 2.")

def start_game():
    """Начало игры и первый выбор."""
    print("## 🗝️ «Тайны Старой Хижины»")
    print("Вы стоите перед **старой, полуразрушенной хижиной** посреди густого, тёмного леса. Сгущаются сумерки, и вы слышите далёкий вой. Вам нужно найти убежище на ночь.")
    print("-" * 20)
    
    inventory = []
    
    while True:
        print("\n**1.** Что вы делаете?")
        print("1. Постучать в дверь хижины.")
        print("2. Поискать другой путь или обходной вход.")
        print("3. Попробовать отыскать что-нибудь полезное снаружи (взаимодействие с предметом).")
        
        choice = input("*(Введите 1, 2 или 3): *").strip()
        
        if choice == '1':
            path_knock(inventory)
            break
        elif choice == '2':
            path_search_entrance(inventory)
            break
        elif choice == '3':
            path_search_outside(inventory)
            break
        else:
            print("Неверный ввод. Пожалуйста, введите 1, 2 или 3.")


# Запуск игры
if __name__ == "__main__":
    start_game()